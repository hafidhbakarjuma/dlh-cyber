#!/usr/bin/env python3
import sys
import json
import argparse
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

try:
    from enrich_ioc import enrich_ioc, detect_ioc_type
    import case_manager
except ImportError as e:
    print(f"Error importing required local modules: {e}", file=sys.stderr)
    sys.exit(1)

def main():
    parser = argparse.ArgumentParser(description="Phishing Triage Automation Playbook")
    parser.add_argument("alert_path", help="Path to phishing alert JSON file")
    args = parser.parse_args()

    # 1. Load Alert JSON
    try:
        with open(args.alert_path, "r") as f:
            alert = json.load(f)
    except Exception as e:
        print(f"Error: Unrecoverable error reading alert file {args.alert_path}: {e}", file=sys.stderr)
        sys.exit(1)

    alert_id = alert.get("alert_id") or alert.get("id")
    if not alert_id:
        print("Error: Missing required field 'alert_id' in alert JSON", file=sys.stderr)
        sys.exit(1)

    rule_name = alert.get("rule_name") or alert.get("rule", "phishing_email_suspicious_sender")
    raw_log = alert.get("raw_log", {})

    extracted_items = []
    seen_values = set()

    # Extract from_ip
    from_ip = raw_log.get("from_ip")
    if from_ip:
        extracted_items.append({"value": from_ip.strip(), "hint": "ipv4"})

    # Extract email domain from 'from' field
    from_header = raw_log.get("from", "")
    if "@" in from_header:
        domain_part = from_header.split("@")[-1].strip().strip(">").strip()
        if domain_part:
            extracted_items.append({"value": domain_part, "hint": "domain"})

    # Extract body_urls
    body_urls = raw_log.get("body_urls", [])
    for url in body_urls:
        if not isinstance(url, str):
            continue
        try:
            parsed = urlparse(url if "://" in url else "http://" + url)
            hostname = parsed.hostname
            if hostname:
                extracted_items.append({"value": hostname, "hint": None})
            else:
                print(f"Warning: Malformed URL in body_urls (no hostname): {url}", file=sys.stderr)
        except Exception as ex:
            print(f"Warning: Failed to parse URL '{url}': {ex}", file=sys.stderr)

    total_extracted = len(extracted_items)
    enriched_results = []
    verdict_counts = {"BLOCK": 0, "INVESTIGATE": 0, "ALLOW": 0}

    # Process and deduplicate IOCs
    for item in extracted_items:
        val = item["value"]
        if val in seen_values:
            enriched_results.append({
                "ioc": val,
                "type": item["hint"] or detect_ioc_type(val),
                "skipped": True,
                "verdict": "SKIPPED"
            })
            continue

        seen_values.add(val)
        try:
            res = enrich_ioc(val)
        except Exception as ex:
            print(f"Warning: enrich_ioc failed for {val}: {ex}", file=sys.stderr)
            res = {
                "ioc": val,
                "type": item["hint"] or detect_ioc_type(val),
                "ip_class": "unknown",
                "reverse_dns": "ERROR",
                "feed_result": {"in_malicious_feed": False, "in_benign_list": False},
                "score": 30,
                "verdict": "INVESTIGATE",
                "enriched_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            }
        
        enriched_results.append(res)
        v = res.get("verdict", "INVESTIGATE")
        if v in verdict_counts:
            verdict_counts[v] += 1

    # Apply Decision Logic
    has_block = any(r.get("verdict") == "BLOCK" for r in enriched_results if not r.get("skipped"))
    has_investigate = any(r.get("verdict") == "INVESTIGATE" for r in enriched_results if not r.get("skipped"))

    if has_block:
        playbook_verdict = "ESCALATE"
        case_severity = "Critical"
        case_status = "escalated"
        action_desc = "SOC notification queued for on-call analyst"
    elif has_investigate:
        playbook_verdict = "REVIEW"
        case_severity = "High"
        case_status = "open"
        action_desc = "Queued for manual analyst review"
    else:
        playbook_verdict = "CLOSE"
        case_severity = "Low"
        case_status = "closed"
        action_desc = "Auto-closed: No indicators of compromise"

    # Prepare IOC list for case creation
    case_iocs = []
    for r in enriched_results:
        if r.get("skipped"):
            continue
        case_iocs.append({
            "ioc_value": r.get("ioc"),
            "ioc_type": r.get("type"),
            "verdict": r.get("verdict"),
            "score": r.get("score", 0)
        })

    case_title = alert.get("title") or f"Phishing: {rule_name.replace('_', ' ').title()}"
    case_desc = alert.get("description") or f"Phishing alert generated by rule {rule_name} with {len(case_iocs)} unique IOCs."

    try:
        case_id = case_manager.create_case(
            alert_id=alert_id,
            severity=case_severity,
            title=case_title,
            description=case_desc,
            iocs=case_iocs
        )
    except Exception as e:
        print(f"Error: Failed to create case in database: {e}", file=sys.stderr)
        sys.exit(1)

    if playbook_verdict == "CLOSE":
        try:
            case_manager.close_case(case_id, "no_indicators_of_compromise")
        except Exception as e:
            print(f"Error closing case {case_id}: {e}", file=sys.stderr)

    elif playbook_verdict == "ESCALATE":
        try:
            case_manager.update_case_status(case_id, "escalated")
            trigger_ioc = next((r["ioc"] for r in enriched_results if r.get("verdict") == "BLOCK"), "Unknown")
            case_manager.add_case_note(case_id, f"Escalated due to malicious IOC: {trigger_ioc} (BLOCK verdict)")
        except Exception as e:
            print(f"Error updating case status/notes for {case_id}: {e}", file=sys.stderr)

    now_utc_str = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    audit_line = f"{now_utc_str} | PHISHING_TRIAGE | {alert_id} | IOCs:{len(seen_values)} | BLOCK:{verdict_counts['BLOCK']},INVESTIGATE:{verdict_counts['INVESTIGATE']},ALLOW:{verdict_counts['ALLOW']} | Verdict:{playbook_verdict} | Case:{case_id} | Severity:{case_severity}"
    
    try:
        with open("playbook_audit.log", "a") as log_f:
            log_f.write(audit_line + "\n")
    except Exception as e:
        print(f"Warning: Failed to write to playbook_audit.log: {e}", file=sys.stderr)

    # Print structured summary to stdout
    print(f"[{now_utc_str}] PHISHING TRIAGE PLAYBOOK")
    print(f"Alert      : {alert_id}")
    print(f"Rule       : {rule_name}")
    print(f"IOCs       : {total_extracted} extracted, {len(seen_values)} enriched")
    
    for r in enriched_results:
        if r.get("skipped"):
            print(f"  {r['ioc']:<22} [dedup, skipped]")
        else:
            val = r.get("ioc")
            t = r.get("type")
            verd = r.get("verdict")
            score = r.get("score", 0)
            feed_res = r.get("feed_result", {})
            cat = feed_res.get("category", "")
            tags = feed_res.get("tags", [])
            tag_str = f"({cat}, {', '.join(tags)})" if cat or tags else ""
            print(f"  {val:<22} {t:<7} {verd:<11} score={score:<3} {tag_str}")

    print(f"Verdict    : {playbook_verdict}")
    print(f"Case       : {case_id}  Severity: {case_severity}  Status: {case_status}")
    print(f"Action     : {action_desc}")

if __name__ == "__main__":
    main()
